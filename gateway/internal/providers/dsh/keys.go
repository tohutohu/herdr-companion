package dsh

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// The route the built-in DeepSeek models use. Its key is Config.APIKey,
// passed to DSH as DEEPSEEK_API_KEY.
const DeepSeekRoute = deepSeekRoute

const patchName = "gateway-providers.patch.yml"

// keyEnv names the variable that carries a route's API key to the DSH
// child. The patch refers to it by name, so no key is written to disk.
func keyEnv(route string) string {
	return "HERDR_DSH_KEY_" + strings.ToUpper(strings.ReplaceAll(route, "-", "_"))
}

func validateProviderKeys(keys map[string]string) error {
	for route, key := range keys {
		if !routePattern.MatchString(route) || route == deepSeekRoute {
			return fmt.Errorf("invalid DSH provider %q", route)
		}
		if key == "" || strings.ContainsAny(key, "\x00\r\n") {
			return fmt.Errorf("invalid API key for DSH provider %q", route)
		}
	}
	return nil
}

// providerPatch enables DSH's pi-ai adapter for each keyed route. The
// installed pi-ai catalog supplies endpoints and models. This overlay
// replaces any llm-pi-ai configuration in the DSH home.
func providerPatch(keys map[string]string) []byte {
	routes := make([]string, 0, len(keys))
	for route := range keys {
		routes = append(routes, route)
	}
	sort.Strings(routes)
	var b strings.Builder
	b.WriteString("# Generated by Herdr Companion Gateway from dshProviderKeys; edits are overwritten.\n")
	b.WriteString("- id: llm-pi-ai\n  config:\n    providers:\n")
	for _, route := range routes {
		fmt.Fprintf(&b, "      %s:\n        apiKeyEnv: %s\n", route, keyEnv(route))
	}
	return []byte(b.String())
}

// writePatch keeps the overlay in the Gateway's DSH state directory in step
// with the configured keys, and returns its path ("" when unused).
func writePatch(dir string, keys map[string]string) (string, error) {
	path := filepath.Join(dir, patchName)
	if len(keys) == 0 {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return "", err
		}
		return "", nil
	}
	if err := os.WriteFile(path+".tmp", providerPatch(keys), 0600); err != nil {
		return "", err
	}
	return path, os.Rename(path+".tmp", path)
}
